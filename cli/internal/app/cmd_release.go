package app

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/sealedtempo/sealed/cli/internal/deploy"
	"github.com/sealedtempo/sealed/runtime/composer"
)

const releaseUsage = `Usage:
  sealed release build <app> [--catalog <catalog/apps>] [--out <bundle.tar>] [--sbom-dir <dir>] [--scan-dir <dir>]
  sealed release build <app> --check <version|latest> [--catalog <catalog/apps>]

build packs catalog/apps/<app> into the deterministic release bundle and prints bundleHash, egressPolicyHash,
sbomHash and releaseId (the publishRelease arguments). With --check it rebuilds a published release: the SBOMs
and scans come from the published bundle (they are generated by CI), everything else from your checkout, and
the result must equal the onchain bundleHash byte for byte.

A manifest image whose digest is still the all-zero placeholder (D-028) cannot boot, so build refuses it unless
--dev-allow-unbuilt is given with SEALED_DEV_SIM=1 (local devnets only; such a bundle is never a real release).

The output also names where the release's assets are published under the release asset base (D-046): the
bundle, its signature, certificate and provenance, and each image's SBOM.
`

func runRelease(ctx context.Context, args []string, e *Env) error {
	if len(args) == 0 || args[0] != "build" {
		fmt.Fprint(e.Stderr, releaseUsage)
		if len(args) > 0 && (args[0] == "-h" || args[0] == "--help") {
			return nil
		}
		return usagef("usage: sealed release build <app>")
	}
	fs := newFlags("sealed release build", e)
	var c commonFlags
	c.register(fs)
	var catalog, out, sbomDir, scanDir, check, registryRef string
	var allowMissingSBOM, devUnbuilt bool
	fs.StringVar(&catalog, "catalog", filepath.Join("catalog", "apps"), "catalog apps directory")
	fs.StringVar(&out, "out", "", "write the bundle tar here")
	fs.StringVar(&sbomDir, "sbom-dir", "", "directory with <image>.spdx.json (default <app>/sbom, or the published bundle's with --check)")
	fs.StringVar(&scanDir, "scan-dir", "", "directory with <image>.json scan reports")
	fs.StringVar(&check, "check", "", "rebuild a published release (a version or latest) and compare with its onchain bundleHash")
	fs.StringVar(&registryRef, "registry", "", "image registry for the bundled refs (default catalog.registry)")
	fs.BoolVar(&allowMissingSBOM, "allow-missing-sbom", false, "local development only: build without SBOMs")
	fs.BoolVar(&devUnbuilt, "dev-allow-unbuilt", false, "DEV ONLY (SEALED_DEV_SIM=1): build bundles whose images still have the all-zero placeholder digest")
	pos, err := parse(fs, args[1:])
	if err != nil {
		return err
	}
	if len(pos) != 1 {
		return usagef("usage: sealed release build <app>")
	}
	if devUnbuilt && e.getenv("SEALED_DEV_SIM") != "1" {
		return usagef("--dev-allow-unbuilt needs SEALED_DEV_SIM=1 (never for a real release)")
	}
	app := pos[0]
	appDir := filepath.Join(catalog, app)
	if st, err := os.Stat(filepath.Join(appDir, composer.ManifestFile)); err != nil || st.IsDir() {
		return fmt.Errorf("%s has no %s (use --catalog)", appDir, composer.ManifestFile)
	}
	s, err := c.settings(e)
	if err != nil {
		return err
	}
	if registryRef == "" {
		registryRef = s.Defaults.Catalog.Registry
	}
	in := composer.BuildInput{AppDir: appDir, SBOMDir: sbomDir, ScanDir: scanDir, Registry: registryRef, AllowMissingSBOM: allowMissingSBOM}

	var published []byte
	var onchainHash composer.Hash
	var onchainVersion string
	if check != "" {
		reader, err := e.chain(ctx, s)
		if err != nil {
			return err
		}
		rel, err := deploy.ResolveRelease(ctx, reader, deploy.App{ID: app, Release: check})
		if err != nil {
			return err
		}
		onchainHash, onchainVersion = rel.BundleHash, rel.Version
		if published, err = c.fetcher(e, s).Fetch(ctx, app, rel.Version, rel.BundleHash); err != nil {
			return err
		}
		files, err := composer.ReadTar(published)
		if err != nil {
			return err
		}
		tmp, err := os.MkdirTemp("", "sealed-release-*")
		if err != nil {
			return err
		}
		defer os.RemoveAll(tmp)
		for prefix, dst := range map[string]*string{"sbom/": &in.SBOMDir, "scan/": &in.ScanDir} {
			if *dst != "" {
				continue
			}
			dir := filepath.Join(tmp, strings.TrimSuffix(prefix, "/"))
			if err := os.MkdirAll(dir, 0o700); err != nil {
				return err
			}
			for name, b := range files {
				if rest, ok := strings.CutPrefix(name, prefix); ok && !strings.Contains(rest, "/") {
					if err := os.WriteFile(filepath.Join(dir, rest), b, 0o600); err != nil {
						return err
					}
				}
			}
			*dst = dir
		}
	}
	b, err := composer.BuildBundle(in)
	if err != nil {
		return err
	}
	if unbuilt := unbuiltImages(b); len(unbuilt) > 0 && !devUnbuilt {
		return fmt.Errorf("%s: images %s still have the all-zero placeholder digest (D-028); a bundle with them cannot boot "+
			"and must not be published (local devnets only: --dev-allow-unbuilt with SEALED_DEV_SIM=1)", app, strings.Join(unbuilt, ", "))
	}
	if out != "" {
		if err := os.WriteFile(out, b.Tar, 0o644); err != nil {
			return err
		}
	}
	info := b.Info()
	doc := map[string]any{"release": info, "bundleBytes": len(b.Tar)}
	base := c.assetBase
	if base == "" {
		base = s.ReleaseAssetBase()
	}
	assets, err := releaseAssetURLs(b, base)
	if err != nil {
		return err
	}
	doc["assets"] = assets
	if unbuilt := unbuiltImages(b); len(unbuilt) > 0 {
		doc["unbuilt"] = unbuilt
	}
	match := true
	var diffs []string
	if check != "" {
		match = b.Hash == onchainHash
		doc["onchainBundleHash"] = onchainHash.Hex()
		doc["onchainVersion"] = onchainVersion
		doc["reproduced"] = match
		if !match {
			diffs = diffBundles(b.Tar, published)
			doc["differences"] = diffs
		}
	}
	if c.json {
		if err := writeJSON(e.Stdout, doc); err != nil {
			return err
		}
	} else {
		e.printf("app              %s\nversion          %s\nappId            %s\nbundleHash       %s\negressPolicyHash %s\nsbomHash         %s\nreleaseId        %s\n",
			info.Slug, info.Version, info.AppID, info.BundleHash, info.EgressPolicyHash, info.SBOMHash, info.ReleaseID)
		if out != "" {
			e.printf("bundle           %s (%d bytes)\n", out, len(b.Tar))
		}
		e.printf("published at     %s\n", assets.Bundle)
		if check != "" {
			if match {
				e.printf("\nreproduced: the bundle equals release %s onchain (bundleHash %s)\n", onchainVersion, onchainHash.Hex())
			} else {
				e.printf("\nNOT reproduced: onchain release %s has bundleHash %s\n", onchainVersion, onchainHash.Hex())
				for _, d := range diffs {
					e.printf("  %s\n", d)
				}
			}
		}
	}
	if !match {
		return &exitError{code: ExitFailed}
	}
	return nil
}

// assetURLs are a release's asset URLs under a release asset base, as release CI publishes them.
type assetURLs struct {
	Tag         string            `json:"tag"`
	Bundle      string            `json:"bundle"`
	Signature   string            `json:"signature"`
	Certificate string            `json:"certificate"`
	Provenance  string            `json:"provenance"`
	SBOM        map[string]string `json:"sbom"`
}

// releaseAssetURLs applies runtime/composer's asset rule (D-046) to a built bundle.
func releaseAssetURLs(b *composer.Bundle, base string) (*assetURLs, error) {
	a, err := b.Assets(base)
	if err != nil {
		return nil, err
	}
	out := &assetURLs{Tag: a.Tag, Bundle: a.Bundle, Signature: a.Signature, Certificate: a.Certificate, Provenance: a.Provenance, SBOM: map[string]string{}}
	for _, img := range b.Manifest.Images {
		u, err := a.SBOM(img.Name)
		if err != nil {
			return nil, err
		}
		out.SBOM[img.Name] = u
	}
	return out, nil
}

// unbuiltImages names the manifest images that still carry the all-zero placeholder digest.
func unbuiltImages(b *composer.Bundle) []string {
	var out []string
	for _, img := range b.Manifest.Images {
		if img.Unbuilt() {
			out = append(out, img.Name)
		}
	}
	return out
}

// diffBundles lists the files that differ between two bundle tars.
func diffBundles(local, published []byte) []string {
	a, errA := composer.ReadTar(local)
	b, errB := composer.ReadTar(published)
	if errA != nil || errB != nil {
		return []string{"the published bundle is not a readable tar"}
	}
	names := map[string]bool{}
	for n := range a {
		names[n] = true
	}
	for n := range b {
		names[n] = true
	}
	var out []string
	for n := range names {
		x, inA := a[n]
		y, inB := b[n]
		switch {
		case !inA:
			out = append(out, "only in the published bundle: "+n)
		case !inB:
			out = append(out, "only in your build: "+n)
		case !bytes.Equal(x, y):
			out = append(out, "differs: "+n)
		}
	}
	sort.Strings(out)
	if len(out) == 0 {
		out = []string{"same files and contents, different tar bytes (entry metadata)"}
	}
	return out
}
