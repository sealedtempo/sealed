/** sealed-stack/v1 as the composer writes it for this config (crm, llm-gateway). */
export function makeStackInfo(config: Config, o: { payer?: boolean } = {}) {
  const hasGateway = o.payer ?? config.apps.some((a) => a.id === "llm-gateway");
  return {
    schema: "sealed-stack/v1",
    composerVersion: "1.0.0",
    apps: config.apps.map((a) => {
      const k = KNOWN_APPS[a.id] ?? { ip: "172.30.0.30", metering: { unit: "pages", source: "callback" }, port: 8080, path: "/healthz" };
      const primary = a.id === "crm" ? "crm-server" : `${a.id}-proxy`;
      return {
        id: a.id,
        appId: appId(a.id),
        releaseId: a.releaseId.toLowerCase(),
        version: "1.0.0",
        primaryService: primary,
        services: [{ name: primary, ip: k.ip, primary: true }, ...(k.extra ?? []).map((e) => ({ ...e, primary: false }))],
        secrets: [],
        metering: k.metering,
        healthcheck: { service: primary, port: k.port, path: k.path },
        routes: [],
        // crm declares an owner for its database volume (manifest x-sealed-owner, brief item 11).
        volumes:
          a.id === "crm"
            ? [
                { name: "db", path: "/mnt/sealed-data/crm/db", owner: "999:999" },
                { name: "files", path: "/mnt/sealed-data/crm/files" },
              ]
            : [],
      };
    }),
    dataRoot: "/mnt/sealed-data",
    dataDirs: config.apps.some((a) => a.id === "crm") ? ["/mnt/sealed-data/crm/db", "/mnt/sealed-data/crm/files"] : [],
    sidecars: {
      caddy: IPS.caddy,
      "sealed-agent": IPS.agent,
      "sealed-egress": IPS.egress,
      ...(hasGateway ? { "sealed-mpp-payer": IPS.payer, "sealed-verifierd": IPS.verifierd } : {}),
    },
    attestHost: "attest.34-1-2-3.sslip.io",
    gate: { username: "sealed", secretApp: "_gate", secret: "GATE_PASSWORD_BCRYPT" },
    caddy: {
      adminSocket: "/run/sealed/caddy-admin/admin.sock",
      caddyfile: "/etc/sealed/caddy/Caddyfile",
      caddyfilePaymentNeeded: "/etc/sealed/caddy/Caddyfile.payment-needed",
    },
  };
}

const dollars = (s: string) => s.replaceAll("$", "$$");

/** A secrets tmpfs volume mount as the composer writes it (whole owner directory). */
const secretsVolume = (owner: string, readOnly: boolean) => ({
  type: "volume",
  source: `sealed-secrets-${owner}`,
  target: `/run/sealed/secrets/${owner}`,
  volume: { nocopy: true },
  ...(readOnly ? { read_only: true } : {}),
});

/** app-compose.json in the INTERFACES 6 shape: measured configs, app volumes bound from /mnt/sealed-data. */
export function makeAppCompose(config: Config, o: { stack?: unknown; omit?: string[] } = {}): string {
  const configs: Record<string, { content: string }> = {
    "sealed-config": { content: dollars(canonicalize(config)) },
    "sealed-stack": { content: dollars(canonicalize(o.stack ?? makeStackInfo(config))) },
    "sealed-caddyfile": { content: dollars(CADDYFILE) },
    "sealed-caddyfile-payment-needed": { content: dollars(CADDYFILE_PAYMENT_NEEDED) },
  };
  for (const name of o.omit ?? []) delete configs[name];
  const compose = {
    configs,
    services: {
      "crm-server": {
        image: `ghcr.io/sealed-dev/twenty@sha256:${"00".repeat(32)}`,
        entrypoint: ["/sealed/bin/envexec", "--app", "crm", "--secret", "APP_SECRET", "--", "/app/start"],
        user: "1000:1000",
        volumes: [
          { type: "bind", source: "/mnt/sealed-data/crm/files", target: "/app/files" },
          secretsVolume("crm", true),
        ],
      },
      "crm-db": {
        image: `ghcr.io/sealed-dev/postgres@sha256:${"00".repeat(32)}`,
        volumes: ["/mnt/sealed-data/crm/db:/var/lib/postgresql/data", "/etc/passwd:/etc/passwd:ro"],
      },
      "sealed-agent": {
        image: `ghcr.io/sealed-dev/sealed-agent@sha256:${"00".repeat(32)}`,
        volumes: [
          { type: "bind", source: "/mnt/sealed-data", target: "/mnt/sealed-data", bind: { propagation: "rshared" } },
          ...["_gate", ...config.apps.map((a) => a.id), "sealed-mpp-payer"].map((o) => secretsVolume(o, false)),
        ],
      },
    },
  };
  return canonicalize({
    allowed_envs: [],
    docker_compose_file: canonicalize(compose),
    gateway_enabled: false,
    key_provider: "tpm",
    key_provider_id: "",
    kms_enabled: false,
    local_key_provider_enabled: false,
    manifest_version: 2,
    name: "sealed-12345678",
    no_instance_id: false,
    public_logs: false,
    public_sysinfo: false,
    public_tcbinfo: true,
    runner: "docker-compose",
    secure_time: false,
    storage_fs: "ext4",
  });
}

export const TEST_PEER_HEADER = "x-sealed-test-peer";

/** Lets tests choose the caller IP of a local API request (all test traffic comes from 127.0.0.1). */
export const testPeerOf = (req: http.IncomingMessage): string => {
  const h = req.headers[TEST_PEER_HEADER];
  return typeof h === "string" ? h : normalizePeer(req.socket.remoteAddress);
};

export const fromPeer = (ip: string) => ({ [TEST_PEER_HEADER]: ip });

