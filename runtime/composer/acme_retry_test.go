// Caddy reaches exactly one ACME host through sealed-egress (ACMEHost, the
// only entry of its caller allowlist). certmagic sends every retry after a
// failed first issuance to the issuer's test directory, which defaults to
// Let's Encrypt staging when the main directory is Let's Encrypt production
// (certmagic v0.25.6 acmeissuer.go:194-199 and :448). Egress refuses
// staging, so without an explicit test directory one failed first order
// (a rate limit, an outage, slow ingress) left the VM without a certificate
// until Caddy reloaded (spec-conformance G06).

// acmeIssuerRe matches the composer's global issuer block.
var acmeIssuerRe = regexp.MustCompile(`\n\tcert_issuer acme \{\n\t\tdir (\S+)\n\t\ttest_dir (\S+)\n\t\}\n`)

// globalOptions returns the Caddyfile's global options block (the first
// top-level "{" up to its closing "}").
func globalOptions(t *testing.T, name string, cf []byte) string {
	t.Helper()
	s := string(cf)
	i := strings.Index(s, "\n{\n")
	if i < 0 {
		t.Fatalf("%s: no global options block", name)
	}
	j := strings.Index(s[i:], "\n}\n")
	if j < 0 {
		t.Fatalf("%s: global options block not closed", name)
	}
	return s[i : i+j+3]
}

// TestCaddyfileACMEIssuerStaysOnAllowedHost checks, in both measured
// Caddyfiles, that the ACME issuer's directory and test directory are the
// same https URL on the one host sealed-egress lets Caddy reach, and that no
// other issuer or CA option can send Caddy elsewhere.
func TestCaddyfileACMEIssuerStaysOnAllowedHost(t *testing.T) {
	cfg, bundles := fixtureStack(t)
	r := mustCompose(t, cfg, bundles...)

	var ec struct {
		Callers []struct {
			Name  string   `json:"name"`
			IP    string   `json:"ip"`
			Allow []string `json:"allow"`
		} `json:"callers"`
	}
	if err := json.Unmarshal(r.EgressConfig, &ec); err != nil {
		t.Fatal(err)
	}
	var caddyAllow []string
	for _, c := range ec.Callers {
		if c.IP == CaddyIP {
			caddyAllow = c.Allow
		}
	}
	if len(caddyAllow) != 1 || caddyAllow[0] != ACMEHost {
		t.Fatalf("caddy's egress allowlist is %v, want only %s", caddyAllow, ACMEHost)
	}

	for name, cf := range map[string][]byte{"Caddyfile": r.Caddyfile, "Caddyfile.payment-needed": r.CaddyfilePaymentNeeded} {
		global := globalOptions(t, name, cf)
		m := acmeIssuerRe.FindStringSubmatch(global)
		if m == nil {
			t.Errorf("%s: no cert_issuer acme block with dir and test_dir in the global options:\n%s", name, global)
			continue
		}
		dir, testDir := m[1], m[2]
		if dir != testDir {
			t.Errorf("%s: test_dir %s differs from dir %s: certmagic sends every retry to test_dir", name, testDir, dir)
		}
		for _, d := range []string{dir, testDir} {
			u, err := url.Parse(d)
			if err != nil || u.Scheme != "https" || u.Port() != "" || u.Host+":443" != ACMEHost || u.Path != "/directory" {
				t.Errorf("%s: ACME directory %s is not https://%s/directory, the host egress allows", name, d, strings.TrimSuffix(ACMEHost, ":443"))
			}
		}
		if n := strings.Count(string(cf), "cert_issuer"); n != 1 {
			t.Errorf("%s: %d cert_issuer lines, want 1 (a second issuer would be tried on another host)", name, n)
		}
		for _, never := range []string{"acme_ca", "zerossl", "local_certs", "\n\t\temail ", "\n\temail "} {
			if strings.Contains(string(cf), never) {
				t.Errorf("%s: has %q", name, strings.TrimSpace(never))
			}
		}
	}
}

// TestACMERetryWithRealCaddy runs the measured Caddyfile in a real Caddy
// (SEALED_CADDY_BIN, v2.11.x) against a local ACME CA reached through a
// CONNECT proxy that, like sealed-egress, lets Caddy reach only ACMEHost.
// The CA refuses the first order for each name with a 429 rate limit, so
// every certificate needs certmagic's first retry, about one minute later.
// The test passes when each site's certificate is issued on that retry from
// the production directory, with its key generated by Caddy and stored
// under the data directory (XDG_DATA_HOME, /data in the VM), and no request
// ever went to another host. On the old template the retry went to Let's
// Encrypt staging and the proxy refused it.
//
// The Caddyfile is the composed file except for three options added to the
// global block (http_port and https_port on free local ports, acme_ca_root
// for the test CA) and the admin socket path. The CA marks authorizations
// valid at once, so no challenge is solved: in the VM, Let's Encrypt
// validates over the public IP, which a local test cannot reproduce.
func TestACMERetryWithRealCaddy(t *testing.T) {
	bin := os.Getenv("SEALED_CADDY_BIN")
	if bin == "" {
		t.Skip("SEALED_CADDY_BIN not set")
	}
	if testing.Short() {
		t.Skip("waits for certmagic's first retry (about one minute)")
	}
	cfg, bundles := fixtureStack(t)
	r := mustCompose(t, cfg, bundles...)
	hosts := siteHosts(r.Caddyfile)
	if len(hosts) == 0 {
		t.Fatal("no site hosts in the Caddyfile")
	}

	acmeName := strings.TrimSuffix(ACMEHost, ":443")
	ca := newTestCA(t)
	acme := newFakeACME(t, ca, "https://"+acmeName)
	srv := httptest.NewUnstartedServer(acme)
	srv.TLS = &tls.Config{Certificates: []tls.Certificate{ca.leaf(t, acmeName)}}
	srv.StartTLS()
	defer srv.Close()

	proxy := newEgressProxy(ACMEHost, srv.Listener.Addr().String())
	proxySrv := httptest.NewServer(proxy)
	defer proxySrv.Close()

	dir, err := os.MkdirTemp("/tmp", "sealed-acme-") // short path for the unix socket
	if err != nil {
		t.Fatal(err)
	}
	defer os.RemoveAll(dir)
	caPEM := filepath.Join(dir, "test-ca.pem")
	if err := os.WriteFile(caPEM, ca.pem(), 0o644); err != nil {
		t.Fatal(err)
	}
	httpPort, httpsPort := freePort(t), freePort(t)
	cf := string(r.Caddyfile)
	cf = strings.Replace(cf, "\n{\n", fmt.Sprintf("\n{\n\thttp_port %d\n\thttps_port %d\n\tacme_ca_root %s\n", httpPort, httpsPort, caPEM), 1)
	cf = strings.ReplaceAll(cf, caddy.DefaultAdminSocket, filepath.Join(dir, "admin.sock"))
	caddyfile := filepath.Join(dir, "Caddyfile")
	if err := os.WriteFile(caddyfile, []byte(cf), 0o644); err != nil {
		t.Fatal(err)
	}

	// Caddy's environment as composed, with the local proxy in place of
	// sealed-egress and local data and config directories.
	env := caddyServiceEnv(t, r.ComposeJSON)
	dataDir := filepath.Join(dir, "data")
	var cmdEnv []string
	for k, v := range env {
		switch k {
		case "XDG_DATA_HOME":
			v = dataDir
		case "XDG_CONFIG_HOME":
			v = filepath.Join(dir, "config")
		}
		cmdEnv = append(cmdEnv, k+"="+strings.ReplaceAll(v, ProxyURL, proxySrv.URL))
	}
	if env["HTTPS_PROXY"] != ProxyURL || env["XDG_DATA_HOME"] != "/data" {
		t.Fatalf("caddy's composed environment changed: %v", env)
	}
	cmdEnv = append(cmdEnv, "HOME="+dir, "PATH="+os.Getenv("PATH"))

	ctx, cancel := context.WithCancel(context.Background())
	cmd := exec.CommandContext(ctx, bin, "run", "--config", caddyfile, "--adapter", "caddyfile")
	cmd.Env = cmdEnv
	var logs syncBuffer
	cmd.Stdout, cmd.Stderr = &logs, &logs
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	exited := make(chan error, 1)
	go func() { exited <- cmd.Wait() }()
	defer func() {
		cancel()
		<-exited
		if t.Failed() {
			t.Logf("caddy logs:\n%s", logs.String())
		}
	}()

	storage := filepath.Join(dataDir, "caddy", "certificates", acmeName+"-directory")
	issued := func() bool {
		for _, h := range hosts {
			for _, ext := range []string{".crt", ".key", ".json"} {
				if _, err := os.Stat(filepath.Join(storage, h, h+ext)); err != nil {
					return false
				}
			}
		}
		return true
	}
	start := time.Now()
	for !issued() {
		if denied := proxy.denied(); len(denied) > 0 {
			t.Fatalf("Caddy asked sealed-egress for %v after %s, which it refuses (only %s is allowed): a retry left the production directory", denied, time.Since(start).Round(time.Second), ACMEHost)
		}
		select {
		case err := <-exited:
			exited <- err
			t.Fatalf("caddy exited: %v", err)
		default:
		}
		if time.Since(start) > 3*time.Minute {
			t.Fatalf("certificates for %v not issued after %s; orders seen: %v", hosts, time.Since(start).Round(time.Second), acme.orderCounts())
		}
		time.Sleep(250 * time.Millisecond)
	}
	t.Logf("certificates for %v issued after %s", hosts, time.Since(start).Round(time.Second))

	if denied := proxy.denied(); len(denied) > 0 {
		t.Errorf("Caddy asked sealed-egress for %v", denied)
	}
	counts := acme.orderCounts()
	for _, h := range hosts {
		// The first order was refused, so the certificate came from the
		// retry. With dir and test_dir equal, certmagic keeps that
		// certificate and orders no second one.
		if counts[h] != 2 {
			t.Errorf("%s: %d orders, want 2 (the refused first order and one retry)", h, counts[h])
		}
		crtPEM, err := os.ReadFile(filepath.Join(storage, h, h+".crt"))
		if err != nil {
			t.Fatal(err)
		}
		keyPEM, err := os.ReadFile(filepath.Join(storage, h, h+".key"))
		if err != nil {
			t.Fatalf("%s: no key under the data directory: %v", h, err)
		}
		block, _ := pem.Decode(crtPEM)
		if block == nil {
			t.Fatalf("%s: certificate is not PEM", h)
		}
		leaf, err := x509.ParseCertificate(block.Bytes)
		if err != nil {
			t.Fatal(err)
		}
		if err := leaf.VerifyHostname(h); err != nil {
			t.Errorf("%s: %v", h, err)
		}
		if err := leaf.CheckSignatureFrom(ca.cert); err != nil {
			t.Errorf("%s: not issued by the test CA: %v", h, err)
		}
		pair, err := tls.X509KeyPair(crtPEM, keyPEM)
		if err != nil {
			t.Errorf("%s: stored key does not match the certificate: %v", h, err)
		} else if !acme.issuedFromCSR(h, pair.Leaf) {
			t.Errorf("%s: stored certificate is not the one issued for Caddy's CSR", h)
		}
	}
	// The ACME account lives next to the certificates, under the production
	// directory's name only.
	accounts, _ := filepath.Glob(filepath.Join(dataDir, "caddy", "acme", "*", "users", "*", "*.key"))
	if len(accounts) != 1 || !strings.Contains(accounts[0], filepath.Join("acme", acmeName+"-directory", "users")) {
		t.Errorf("ACME account keys %v, want one under acme/%s-directory", accounts, acmeName)
	}
	for _, target := range proxy.targets() {
		if target != ACMEHost {
			t.Errorf("proxy saw %s", target)
		}
	}
}

// siteHosts lists the site addresses of a composed Caddyfile.
func siteHosts(cf []byte) []string {
	var hosts []string
	for _, line := range strings.Split(string(cf), "\n") {
		if strings.HasSuffix(line, " {") && !strings.HasPrefix(line, "\t") && !strings.HasPrefix(line, "#") {
			hosts = append(hosts, strings.TrimSuffix(line, " {"))
		}
	}
	sort.Strings(hosts)
	return hosts
}

// caddyServiceEnv returns the composed caddy service's environment.
func caddyServiceEnv(t *testing.T, composeJSON []byte) map[string]string {
	t.Helper()
	var doc struct {
		Services map[string]struct {
			Environment map[string]string `json:"environment"`
		} `json:"services"`
	}
	if err := json.Unmarshal(composeJSON, &doc); err != nil {
		t.Fatal(err)
	}
	env := doc.Services[svcCaddy].Environment
	if len(env) == 0 {
		t.Fatal("caddy service has no environment")
	}
	return env
}

func freePort(t *testing.T) int {
	t.Helper()
	ln, err := net.Listen("tcp", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer ln.Close()
	return ln.Addr().(*net.TCPAddr).Port
}

type syncBuffer struct {
	mu  sync.Mutex
	buf bytes.Buffer
}

func (b *syncBuffer) Write(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buf.Write(p)
}

func (b *syncBuffer) String() string {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.buf.String()
}

// egressProxy plays sealed-egress for Caddy: CONNECT to the one allowed
// host is tunneled to the local ACME server, everything else gets 403.
type egressProxy struct {
	allowed, upstream string
	mu                sync.Mutex
	seen              []string
	refused           []string
}

func newEgressProxy(allowed, upstream string) *egressProxy {
	return &egressProxy{allowed: allowed, upstream: upstream}
}

func (p *egressProxy) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	target := r.Host
	if r.Method != http.MethodConnect {
		target = r.Method + " " + r.URL.String()
	}
	p.mu.Lock()
	p.seen = append(p.seen, target)
	ok := r.Method == http.MethodConnect && r.Host == p.allowed
	if !ok {
		p.refused = append(p.refused, target)
	}
	p.mu.Unlock()
	if !ok {
		http.Error(w, "egress: destination not allowed", http.StatusForbidden)
		return
	}
	up, err := net.Dial("tcp", p.upstream)
	if err != nil {
		http.Error(w, err.Error(), http.StatusBadGateway)
		return
	}
	conn, rw, err := w.(http.Hijacker).Hijack()
	if err != nil {
		up.Close()
		return
	}
	if _, err := conn.Write([]byte("HTTP/1.1 200 Connection established\r\n\r\n")); err != nil {
		conn.Close()
		up.Close()
		return
	}
	go func() {
		_, _ = io.Copy(up, rw.Reader)
		up.Close()
	}()
	_, _ = io.Copy(conn, up)
	conn.Close()
}

func (p *egressProxy) denied() []string {
	p.mu.Lock()
	defer p.mu.Unlock()
	return append([]string(nil), p.refused...)
}

func (p *egressProxy) targets() []string {
	p.mu.Lock()
	defer p.mu.Unlock()
	return append([]string(nil), p.seen...)
}

type testCA struct {
	cert *x509.Certificate
	key  *ecdsa.PrivateKey
}

func newTestCA(t *testing.T) *testCA {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	tmpl := &x509.Certificate{
		SerialNumber:          big.NewInt(1),
		Subject:               pkix.Name{CommonName: "Sealed test ACME CA"},
		NotBefore:             time.Now().Add(-time.Hour),
		NotAfter:              time.Now().Add(365 * 24 * time.Hour),
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageDigitalSignature,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		t.Fatal(err)
	}
	cert, err := x509.ParseCertificate(der)
	if err != nil {
		t.Fatal(err)
	}
	return &testCA{cert: cert, key: key}
}

func (c *testCA) pem() []byte {
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: c.cert.Raw})
}

func (c *testCA) sign(pub crypto.PublicKey, names []string) ([]byte, error) {
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 64))
	if err != nil {
		return nil, err
	}
	tmpl := &x509.Certificate{
		SerialNumber: serial,
		Subject:      pkix.Name{CommonName: names[0]},
		DNSNames:     names,
		NotBefore:    time.Now().Add(-time.Hour),
		NotAfter:     time.Now().Add(90 * 24 * time.Hour),
		KeyUsage:     x509.KeyUsageDigitalSignature,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}
	return x509.CreateCertificate(rand.Reader, tmpl, c.cert, pub, c.key)
}

func (c *testCA) leaf(t *testing.T, name string) tls.Certificate {
	t.Helper()
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		t.Fatal(err)
	}
	der, err := c.sign(&key.PublicKey, []string{name})
	if err != nil {
		t.Fatal(err)
	}
	return tls.Certificate{Certificate: [][]byte{der}, PrivateKey: key}
}

// fakeACME is the smallest RFC 8555 server certmagic and acmez accept. It
// does not check JWS signatures or solve challenges: authorizations are
// valid at once. It refuses the first new order for each name set with a
// 429 rateLimited problem, and issues certificates for the CSRs it gets.
type fakeACME struct {
	t     *testing.T
	ca    *testCA
	base  string
	mu    sync.Mutex
	next  int
	seen  map[string]int // new orders per name set, refused ones included
	order map[int]*fakeOrder
}

type fakeOrder struct {
	names []string
	der   []byte // issued certificate
}

func newFakeACME(t *testing.T, ca *testCA, base string) *fakeACME {
	return &fakeACME{t: t, ca: ca, base: base, seen: map[string]int{}, order: map[int]*fakeOrder{}}
}

func (a *fakeACME) orderCounts() map[string]int {
	a.mu.Lock()
	defer a.mu.Unlock()
	out := map[string]int{}
	for k, v := range a.seen {
		out[k] = v
	}
	return out
}

func (a *fakeACME) issuedFromCSR(name string, leaf *x509.Certificate) bool {
	a.mu.Lock()
	defer a.mu.Unlock()
	for _, o := range a.order {
		if strings.Join(o.names, ",") == name && bytes.Equal(o.der, leaf.Raw) {
			return true
		}
	}
	return false
}

func (a *fakeACME) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	a.mu.Lock()
	a.next++
	nonce := fmt.Sprintf("nonce-%d", a.next)
	a.mu.Unlock()
	w.Header().Set("Replay-Nonce", nonce)
	w.Header().Set("Cache-Control", "no-store")

	if r.URL.Path == "/directory" {
		writeJSON(w, http.StatusOK, map[string]any{
			"newNonce":   a.base + "/new-nonce",
			"newAccount": a.base + "/new-account",
			"newOrder":   a.base + "/new-order",
			"revokeCert": a.base + "/revoke-cert",
			"keyChange":  a.base + "/key-change",
		})
		return
	}
	if r.URL.Path == "/new-nonce" {
		w.WriteHeader(http.StatusOK)
		return
	}
	if r.Method != http.MethodPost {
		problem(w, http.StatusMethodNotAllowed, "malformed", "POST only")
		return
	}
	var jws struct {
		Payload string `json:"payload"`
	}
	if err := json.NewDecoder(r.Body).Decode(&jws); err != nil {
		problem(w, http.StatusBadRequest, "malformed", "not a JWS")
		return
	}
	payload, err := base64.RawURLEncoding.DecodeString(jws.Payload)
	if err != nil {
		problem(w, http.StatusBadRequest, "malformed", "payload")
		return
	}

	account := map[string]any{"status": "valid", "contact": []string{}, "orders": a.base + "/account/1/orders"}
	var id int
	switch {
	case r.URL.Path == "/new-account":
		w.Header().Set("Location", a.base+"/account/1")
		writeJSON(w, http.StatusCreated, account)
	case strings.HasPrefix(r.URL.Path, "/account/"):
		writeJSON(w, http.StatusOK, account)
	case r.URL.Path == "/new-order":
		var req struct {
			Identifiers []struct {
				Type  string `json:"type"`
				Value string `json:"value"`
			} `json:"identifiers"`
		}
		if err := json.Unmarshal(payload, &req); err != nil || len(req.Identifiers) == 0 {
			problem(w, http.StatusBadRequest, "malformed", "identifiers")
			return
		}
		var names []string
		for _, ident := range req.Identifiers {
			names = append(names, ident.Value)
		}
		sort.Strings(names)
		key := strings.Join(names, ",")
		a.mu.Lock()
		a.seen[key]++
		first := a.seen[key] == 1
		if !first {
			a.next++
			id = a.next
			a.order[id] = &fakeOrder{names: names}
		}
		a.mu.Unlock()
		if first {
			w.Header().Set("Retry-After", "1")
			problem(w, http.StatusTooManyRequests, "rateLimited", "too many new orders recently (test: the first order for each name is refused)")
			return
		}
		w.Header().Set("Location", fmt.Sprintf("%s/order/%d", a.base, id))
		writeJSON(w, http.StatusCreated, a.orderJSON(id))
	case sscanf(r.URL.Path, "/order/%d", &id):
		writeJSON(w, http.StatusOK, a.orderJSON(id))
	case sscanf(r.URL.Path, "/authz/%d", &id):
		a.mu.Lock()
		o := a.order[id]
		a.mu.Unlock()
		if o == nil {
			problem(w, http.StatusNotFound, "malformed", "no such authorization")
			return
		}
		writeJSON(w, http.StatusOK, map[string]any{
			"status":     "valid",
			"expires":    time.Now().Add(time.Hour).UTC().Format(time.RFC3339),
			"identifier": map[string]string{"type": "dns", "value": o.names[0]},
			"challenges": []map[string]string{{"type": "http-01", "status": "valid", "url": fmt.Sprintf("%s/chall/%d", a.base, id), "token": "test"}},
		})
	case sscanf(r.URL.Path, "/finalize/%d", &id):
		var req struct {
			CSR string `json:"csr"`
		}
		if err := json.Unmarshal(payload, &req); err != nil {
			problem(w, http.StatusBadRequest, "malformed", "csr")
			return
		}
		raw, err := base64.RawURLEncoding.DecodeString(req.CSR)
		if err != nil {
			problem(w, http.StatusBadRequest, "badCSR", "encoding")
			return
		}
		csr, err := x509.ParseCertificateRequest(raw)
		if err != nil || csr.CheckSignature() != nil {
			problem(w, http.StatusBadRequest, "badCSR", "signature")
			return
		}
		a.mu.Lock()
		o := a.order[id]
		a.mu.Unlock()
		names := append([]string(nil), csr.DNSNames...)
		sort.Strings(names)
		if o == nil || strings.Join(names, ",") != strings.Join(o.names, ",") {
			problem(w, http.StatusBadRequest, "badCSR", "names differ from the order")
			return
		}
		der, err := a.ca.sign(csr.PublicKey, o.names)
		if err != nil {
			problem(w, http.StatusInternalServerError, "serverInternal", err.Error())
			return
		}
		a.mu.Lock()
		o.der = der
		a.mu.Unlock()
		w.Header().Set("Location", fmt.Sprintf("%s/order/%d", a.base, id))
		writeJSON(w, http.StatusOK, a.orderJSON(id))
	case sscanf(r.URL.Path, "/cert/%d", &id):
		a.mu.Lock()
		o := a.order[id]
		a.mu.Unlock()
		if o == nil || o.der == nil {
			problem(w, http.StatusNotFound, "malformed", "no such certificate")
			return
		}
		w.Header().Set("Content-Type", "application/pem-certificate-chain")
		w.WriteHeader(http.StatusOK)
		_ = pem.Encode(w, &pem.Block{Type: "CERTIFICATE", Bytes: o.der})
		_ = pem.Encode(w, &pem.Block{Type: "CERTIFICATE", Bytes: a.ca.cert.Raw})
	default:
		problem(w, http.StatusNotFound, "malformed", "unknown resource "+r.URL.Path)
	}
}

func (a *fakeACME) orderJSON(id int) map[string]any {
	a.mu.Lock()
	defer a.mu.Unlock()
	o := a.order[id]
	if o == nil {
		return map[string]any{"status": "invalid"}
	}
	var idents []map[string]string
	for _, n := range o.names {
		idents = append(idents, map[string]string{"type": "dns", "value": n})
	}
	out := map[string]any{
		"status":         "ready",
		"expires":        time.Now().Add(time.Hour).UTC().Format(time.RFC3339),
		"identifiers":    idents,
		"authorizations": []string{fmt.Sprintf("%s/authz/%d", a.base, id)},
		"finalize":       fmt.Sprintf("%s/finalize/%d", a.base, id),
	}
	if o.der != nil {
		out["status"] = "valid"
		out["certificate"] = fmt.Sprintf("%s/cert/%d", a.base, id)
	}
	return out
}

func sscanf(path, format string, id *int) bool {
	var rest string
	n, _ := fmt.Sscanf(path+" end", format+" %s", id, &rest)
	return n == 2 && rest == "end"
}

func writeJSON(w http.ResponseWriter, status int, v any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(v)
}

func problem(w http.ResponseWriter, status int, typ, detail string) {
	w.Header().Set("Content-Type", "application/problem+json")
	w.WriteHeader(status)
	_ = json.NewEncoder(w).Encode(map[string]any{"type": "urn:ietf:params:acme:error:" + typ, "detail": detail, "status": status})
}
