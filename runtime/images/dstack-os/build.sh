#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
#
# Reproducible build of the Sealed dstack OS image (D-016): upstream dstack at
# the pinned commit, plus patches/ (git am) and overlay/ (one commit), built
# with upstream's own mkosi backend. See README.md.
#
#   build.sh prepare DIR                       fetch upstream into DIR (new), apply patches and overlay
#   build.sh revision                          print the patched commit and tree (prepares in a temp dir)
#   build.sh lock                              rewrite source.lock from a fresh prepare
#   build.sh check-lock DIR                    fail unless DIR is the commit source.lock names
#   build.sh lint DIR                          upstream static contract on the prepared tree
#   build.sh image VARIANT DIR BUILD OUT       build and package (Linux x86-64, root, mkosi on PATH)
#   build.sh package VARIANT DIR BUILD OUT     package an existing build into OUT
#   build.sh rust-inventory VARIANT DIR OUT    license inventory of the Rust crates in the guest (needs cargo)
#
# VARIANT is prod or debug. image and package need OSIMAGE (path to the
# osimage helper, go build ./runtime/images/dstack-os/tools/osimage),
# unsquashfs, mtools and GNU tar. prepare, revision, lock and check-lock run on
# any host with git (macOS included).
set -euo pipefail
umask 0022

SELF=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=SCRIPTDIR/upstream.env
. "$SELF/upstream.env"

die() { echo "build.sh: $*" >&2; exit 1; }

# Isolate every git call from the caller's configuration (signing, hooks,
# am.* options), so the commits it creates are byte-identical everywhere.
sgit() {
  GIT_CONFIG_NOSYSTEM=1 GIT_CONFIG_GLOBAL=/dev/null \
  GIT_AUTHOR_NAME="$SEALED_GIT_NAME" GIT_AUTHOR_EMAIL="$SEALED_GIT_EMAIL" GIT_AUTHOR_DATE="$SEALED_GIT_DATE" \
  GIT_COMMITTER_NAME="$SEALED_GIT_NAME" GIT_COMMITTER_EMAIL="$SEALED_GIT_EMAIL" GIT_COMMITTER_DATE="$SEALED_GIT_DATE" \
    git -c core.autocrlf=false -c core.fileMode=true -c commit.gpgSign=false -c core.hooksPath=/dev/null "$@"
}

prepare() {
  local dir=$1 f rel mode
  [[ ! -e $dir ]] || die "$dir already exists"
  mkdir -p "$dir"
  sgit -C "$dir" init -q
  sgit -C "$dir" remote add origin "$UPSTREAM_REPO"
  sgit -C "$dir" fetch -q --depth=1 origin "$UPSTREAM_COMMIT"
  sgit -C "$dir" checkout -q --detach FETCH_HEAD
  [[ $(sgit -C "$dir" rev-parse HEAD) == "$UPSTREAM_COMMIT" ]] || die "fetched commit is not $UPSTREAM_COMMIT"
  # Patches apply exactly or not at all: git am has no fuzz and no 3-way merge here.
  sgit -C "$dir" am -q --no-3way --keep-cr "$SELF"/patches/[0-9][0-9][0-9][0-9]-*.patch
  # Overlay: files added verbatim. Build scripts are executable, the rest is not.
  (cd "$SELF/overlay" && find . -type f | LC_ALL=C sort) | while IFS= read -r f; do
    rel=${f#./}
    mode=0644
    case $rel in *-build.sh) mode=0755 ;; esac
    mkdir -p "$dir/$(dirname "$rel")"
    install -m "$mode" "$SELF/overlay/$rel" "$dir/$rel"
  done
  # sealed-logship sources (Go, standard library only) become their own module.
  mkdir -p "$dir/os/sealed/logship"
  for f in "$SELF"/logship/*.go; do
    case $f in *_test.go) continue ;; esac
    install -m 0644 "$f" "$dir/os/sealed/logship/"
  done
  printf 'module sealed.dev/logship\n\ngo 1.26\n' > "$dir/os/sealed/logship/go.mod"
  sgit -C "$dir" add -A os
  sgit -C "$dir" commit -q -m "sealed: overlay $SEALED_OS_VERSION

Adds the sealed-debug mkosi profile, the sealed-logship component and the
sealed-logship sources (os/sealed/logship) from runtime/images/dstack-os in
the Sealed public repository."
  sgit -C "$dir" diff --quiet HEAD || die "prepared tree is dirty"
}

revision_of() {
  echo "SEALED_SOURCE_COMMIT=$(sgit -C "$1" rev-parse HEAD)"
  echo "SEALED_SOURCE_TREE=$(sgit -C "$1" rev-parse 'HEAD^{tree}')"
}

with_temp_prepare() {
  local tmp
  tmp=$(mktemp -d "${TMPDIR:-/tmp}/sealed-os-src.XXXXXX")
  # shellcheck disable=SC2064 # expand now: the trap must remove this directory
  trap "rm -rf '$tmp'" EXIT
  prepare "$tmp/src" >&2
  "$@" "$tmp/src"
}

check_lock() {
  local dir=$1 want got
  [[ -f $SELF/source.lock ]] || die "source.lock is missing; run build.sh lock"
  want=$(grep -E '^SEALED_SOURCE_(COMMIT|TREE)=' "$SELF/source.lock")
  got=$(revision_of "$dir")
  if [[ $want != "$got" ]]; then
    echo "source.lock:" >&2; echo "$want" >&2
    echo "prepared:" >&2; echo "$got" >&2
    die "the prepared source does not match source.lock; run build.sh lock and commit it"
  fi
  echo "source matches source.lock: $(sgit -C "$dir" rev-parse HEAD)"
}

write_lock() {
  {
    echo "# Generated by build.sh lock. The patched upstream commit the image is built"
    echo "# from: $UPSTREAM_COMMIT plus patches/ and overlay/. CI fails if it drifts."
    revision_of "$1"
  } > "$SELF/source.lock"
  cat "$SELF/source.lock"
}

lint() {
  local dir=$1
  "$dir/os/mkosi/build.sh" lint
  bash -n "$dir/os/mkosi/components/sealed-logship/sealed-logship.sh" \
    "$dir/os/mkosi/components/sealed-logship/sealed-logship-build.sh"
  # The profile must keep inheriting prod: it adds, it never replaces.
  grep -qx 'Environment=SEALED_IMAGE_VARIANT=debug' "$dir/os/mkosi/mkosi.profiles/sealed-debug/mkosi.conf"
  if grep -Eq '^(Packages|RemoveFiles|ExtraTrees)=' "$dir/os/mkosi/mkosi.profiles/sealed-debug/mkosi.conf"; then
    die "the sealed-debug profile must not change packages or removals"
  fi
  for component in nvidia zfs nvattest; do
    if grep -Eq "^  $component\$" "$dir/os/mkosi/scripts/build-components.sh"; then
      die "component $component is still in the build list"
    fi
  done
  echo "sealed lint passed"
}

variant_vars() {
  case $1 in
    prod) FLAVORS=prod; NAME=$SEALED_IMAGE_NAME_PROD ;;
    debug) FLAVORS=prod,sealed-debug; NAME=$SEALED_IMAGE_NAME_DEBUG ;;
    *) die "variant must be prod or debug, not $1" ;;
  esac
}

image() {
  local variant=$1 dir=$2 build=$3 out=$4
  variant_vars "$variant"
  [[ $(uname -s) == Linux && $(uname -m) == x86_64 ]] || die "image builds need x86-64 Linux"
  [[ $(id -u) == 0 ]] || die "image builds run as root (mkosi needs loop devices and mounts)"
  [[ ! -e $build ]] || die "$build already exists; builds always start from an empty directory"
  if [[ ${SEALED_ALLOW_UNLOCKED:-0} != 1 ]]; then check_lock "$dir"; fi
  echo "building $NAME $SEALED_OS_VERSION (mkosi profiles $FLAVORS)"
  FLAVORS=$FLAVORS JOBS=${JOBS:-$(nproc)} "$dir/os/mkosi/build.sh" --no-cache image "$build"
  package "$variant" "$dir" "$build" "$out"
}

package() {
  local variant=$1 dir=$2 build=$3 out=$4 dist img base uki tmp off sde commit
  variant_vars "$variant"
  : "${OSIMAGE:?set OSIMAGE to the osimage helper binary}"
  # shellcheck source=/dev/null
  DSTACK_VERSION=$(. "$dir/os/mkosi/versions.env" && echo "$DSTACK_VERSION")
  dist="$build/out/$FLAVORS"
  img="$dist/dstack-$DSTACK_VERSION"
  [[ -s $img/disk.raw ]] || die "no assembled image at $img"
  mkdir -p "$out"
  base="$NAME-$SEALED_OS_VERSION"
  commit=$(sgit -C "$dir" rev-parse HEAD)
  sde=$(sgit -C "$dir" log -1 --format=%ct)
  tmp=$(mktemp -d)
  # shellcheck disable=SC2064
  trap "rm -rf '$tmp'" EXIT

  # GCE import format: a gzip'd GNU tar holding exactly disk.raw. Not sparse,
  # sorted, fixed owner and mtime, gzip without a name or time: the tarball is
  # a pure function of disk.raw.
  echo "writing $out/$base-gce.tar.gz"
  tar --format=oldgnu --sort=name --owner=0 --group=0 --numeric-owner \
    --mtime="@$sde" -C "$img" -cf - disk.raw | gzip -n -6 > "$out/$base-gce.tar.gz"

  # The UKI exactly as it sits in the ESP of the boot disk.
  off=$(python3 -I -c '
import struct, sys, zlib
with open(sys.argv[1], "rb") as f:
    f.seek(512); h = f.read(92)
    lba, n, size = struct.unpack_from("<QII", h, 72)
    f.seek(lba * 512); t = f.read(n * size)
for i in range(n):
    e = t[i * size:(i + 1) * size]
    if e[56:128].decode("utf-16-le").rstrip("\0") == "EFI System Partition":
        print(struct.unpack_from("<Q", e, 32)[0] * 512); break
' "$img/disk.raw")
  [[ -n $off ]] || die "no EFI System Partition in disk.raw"
  uki="$tmp/BOOTX64.EFI"
  mcopy -n -i "$img/disk.raw@@$off" ::/EFI/BOOT/BOOTX64.EFI "$uki"

  "$OSIMAGE" identity -dir "$img" -uki "$uki" -gce-tarball "$out/$base-gce.tar.gz" \
    -name "$NAME" -variant "$variant" -version "$SEALED_OS_VERSION" \
    -upstream-repo "$UPSTREAM_REPO" -upstream-tag "$UPSTREAM_TAG" -upstream-commit "$UPSTREAM_COMMIT" \
    -source-commit "$commit" -source-tree "$(sgit -C "$dir" rev-parse 'HEAD^{tree}')" \
    > "$tmp/image-identity.json"

  # Identity bundle: everything import-and-measure.sh and verifiers need
  # without the 1 GB disk (os_image_hash preimage, measurements, metadata).
  local files=() name
  for name in digest.txt sha256sum.txt metadata.json auth_hash.txt measurement.tdx.cbor \
    measurement.snp.cbor measurement.gcp.cbor measurement.aws.cbor measurement.aws.replay.json; do
    [[ -f $img/$name ]] && files+=("dstack-$DSTACK_VERSION/$name")
  done
  cp "$tmp/image-identity.json" "$out/$base-identity.json"
  tar --sort=name --owner=0 --group=0 --numeric-owner --mtime="@$sde" \
    -C "$tmp" -cf "$tmp/identity.tar" image-identity.json
  tar --sort=name --owner=0 --group=0 --numeric-owner --mtime="@$sde" \
    -C "$dist" -rf "$tmp/identity.tar" "${files[@]}"
  gzip -n -9 < "$tmp/identity.tar" > "$out/$base-identity.tar.gz"

  # License and attack-surface check of the exact disk being published. It
  # fails the build on any NVIDIA, ZFS or CDDL content (D-016, D-021).
  python3 -I -B "$SELF/check_image.py" "$img/disk.raw" "$dist/dstack-sealed-inventory" \
    "$out/$base-license-inventory.json" --variant "$variant" --exceptions "$SELF/license-exceptions.json"

  local os_image_hash listed=()
  os_image_hash=$(cat "$img/digest.txt")
  for name in gce.tar.gz identity.tar.gz identity.json license-inventory.json rust-crates.json; do
    [[ -f $out/$base-$name ]] && listed+=("$base-$name")
  done
  (cd "$out" && sha256sum "${listed[@]}") > "$out/$base.sha256"
  {
    echo "image            $NAME $SEALED_OS_VERSION ($variant)"
    echo "source_commit    $commit"
    echo "os_image_hash    $os_image_hash"
    echo "gcp_uki_auth     $(cat "$img/auth_hash.txt")"
    echo "uki_auth_sha384  $("$OSIMAGE" authenticode -alg sha384 "$uki")"
    echo "disk_raw_sha256  $(sha256sum "$img/disk.raw" | cut -d' ' -f1)"
    cat "$out/$base.sha256"
  } | tee "$out/$base-hashes.txt"
}

# Rust crates compiled into the guest (dstack-guest-agent, dstack-util,
# dstack-volume), resolved from the locked Cargo.lock. Runs as a normal user
# before the root image build; package lists the result in the sha256 file.
rust_inventory() {
  local variant=$1 dir=$2 out=$3
  variant_vars "$variant"
  mkdir -p "$out"
  # Any recent cargo resolves the lock file; nothing is compiled.
  (cd "$dir/dstack" && cargo "+${CARGO_TOOLCHAIN:-stable}" metadata --format-version 1 --locked \
    --filter-platform x86_64-unknown-linux-gnu) |
    python3 -I -B "$SELF/rust_inventory.py" "$out/$NAME-$SEALED_OS_VERSION-rust-crates.json"
}

cmd=${1:-}
[[ -n $cmd ]] || die "usage: build.sh prepare|revision|lock|check-lock|lint|image|package|rust-inventory ..."
shift
case $cmd in
  prepare) [[ $# == 1 ]] || die "usage: build.sh prepare DIR"; prepare "$1"; revision_of "$1" ;;
  revision) with_temp_prepare revision_of ;;
  lock) with_temp_prepare write_lock ;;
  check-lock) [[ $# == 1 ]] || die "usage: build.sh check-lock DIR"; check_lock "$1" ;;
  lint) [[ $# == 1 ]] || die "usage: build.sh lint DIR"; lint "$1" ;;
  image) [[ $# == 4 ]] || die "usage: build.sh image VARIANT DIR BUILD OUT"; image "$@" ;;
  package) [[ $# == 4 ]] || die "usage: build.sh package VARIANT DIR BUILD OUT"; package "$@" ;;
  rust-inventory) [[ $# == 3 ]] || die "usage: build.sh rust-inventory VARIANT DIR OUT"; rust_inventory "$@" ;;
  *) die "unknown command $cmd" ;;
esac
