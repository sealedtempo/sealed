#!/usr/bin/env node
// Regenerates src/abis/*.ts from the Foundry ABI exports (contracts/abi/*.json).
//   node scripts/refresh-abis.mjs [abiDir]     default: ../../contracts/abi (the merged repo layout)
// Writes `export const <name>Abi = [...] as const` so viem infers function and event types.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const src = resolve(process.argv[2] ?? join(pkg, "../../contracts/abi"));
const out = join(pkg, "src/abis");
const CONTRACTS = [
  "PlatformRegistry",
  "AppRegistry",
  "DeploymentRegistry",
  "FeeSplitter",
  "OracleSignatureVerifier",
  "IAttestationVerifier",
];

const lowerFirst = (s) => (s.startsWith("I") && /[A-Z]/.test(s[1]) ? "i" + s.slice(1) : s[0].toLowerCase() + s.slice(1));

await mkdir(out, { recursive: true });
const exports = [];
for (const name of CONTRACTS) {
  const abi = JSON.parse(await readFile(join(src, `${name}.json`), "utf8"));
  if (!Array.isArray(abi)) throw new Error(`${name}.json is not an ABI array`);
  const ident = `${lowerFirst(name)}Abi`;
  const body =
    `// Generated by scripts/refresh-abis.mjs from contracts/abi/${name}.json. Do not edit.\n` +
    `export const ${ident} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  await writeFile(join(out, `${name}.ts`), body);
  exports.push(`export { ${ident} } from "./${name}.js";`);
  console.log(`src/abis/${name}.ts (${abi.length} entries)`);
}
await writeFile(join(out, "index.ts"), `// Generated by scripts/refresh-abis.mjs. Do not edit.\n${exports.join("\n")}\n`);
