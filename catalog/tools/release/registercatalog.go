package main

import (
	"encoding/json"
	"fmt"
	"os"
	"regexp"
	"strings"
)

var addressRe = regexp.MustCompile(`^0x[0-9a-fA-F]{40}$`)

// CatalogApp is one entry of the contracts/script/RegisterCatalog.s.sol catalog format.
type CatalogApp struct {
	Slug               string `json:"slug"`
	Name               string `json:"name"`
	LicenseSPDX        string `json:"licenseSpdx"`
	Maintainer         string `json:"maintainer,omitempty"` // omitted: MAINTAINER_DEFAULT_ADDRESS
	MaintainerShareBps int    `json:"maintainerShareBps"`
	MetadataURI        string `json:"metadataURI"`
}

// RegisterCatalogFile is the JSON that RegisterCatalog.s.sol reads (CATALOG_FILE).
type RegisterCatalogFile struct {
	Comment string            `json:"_comment"`
	Images  []json.RawMessage `json:"images"`
	Apps    []CatalogApp      `json:"apps"`
}

// RegisterCatalog builds the RegisterCatalog.s.sol input for the given top-level apps (all when ids is
// empty). Images come verbatim from imagesFile (a JSON array in the script's image format) when set.
// The maintainer is the manifest's payout address unless it is the ${MAINTAINER_DEFAULT_ADDRESS}
// placeholder, in which case the script falls back to MAINTAINER_DEFAULT_ADDRESS.
func RegisterCatalog(d Defaults, apps []App, ids []string, imagesFile string) (*RegisterCatalogFile, error) {
	out := &RegisterCatalogFile{
		Comment: "Generated by catalog/tools/release catalog-json from catalog/apps/*/manifest.yaml. Not committed.",
		Images:  []json.RawMessage{},
		Apps:    []CatalogApp{},
	}
	want := map[string]bool{}
	for _, id := range ids {
		if id = strings.TrimSpace(id); id != "" {
			want[id] = true
		}
	}
	for _, a := range apps {
		if a.Nested || (len(want) > 0 && !want[a.ID]) {
			continue
		}
		delete(want, a.ID)
		m := a.Manifest
		c := CatalogApp{Slug: a.ID, Name: m.Name, LicenseSPDX: m.Upstream.LicenseSPDX, MaintainerShareBps: m.MaintainerShareBps,
			MetadataURI: d.RepoURL() + "/tree/main/" + a.Dir}
		if addressRe.MatchString(m.Maintainer.PayoutAddress) {
			c.Maintainer = strings.ToLower(m.Maintainer.PayoutAddress)
		}
		if c.MaintainerShareBps < 0 || c.MaintainerShareBps > 5000 {
			return nil, fmt.Errorf("%s: maintainer_share_bps %d is outside 0..5000", a.ID, c.MaintainerShareBps)
		}
		out.Apps = append(out.Apps, c)
	}
	if len(want) > 0 {
		return nil, fmt.Errorf("no app %s under %s", strings.Join(sortedKeys(want), ", "), CatalogDir)
	}
	if imagesFile != "" {
		raw, err := os.ReadFile(imagesFile)
		if err != nil {
			return nil, err
		}
		if err := json.Unmarshal(raw, &out.Images); err != nil {
			return nil, fmt.Errorf("%s: want a JSON array of RegisterCatalog images: %w", imagesFile, err)
		}
	}
	return out, nil
}
